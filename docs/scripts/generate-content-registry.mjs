#!/usr/bin/env node
// Scans src/content/<locale>/**/*.mdx and generates src/content/registry.ts,
// a static map of { [locale]: { [slug]: MDXComponent } } plus the list of
// static params for the [locale]/[[...slug]] route. Regenerated on predev /
// prebuild, so adding a new language is just: drop MDX files under
// src/content/<newLocale>/ and add the locale to src/i18n/routing.ts.
import {mkdirSync, readdirSync, statSync, writeFileSync} from 'node:fs'
import {dirname, join, relative, resolve, sep} from 'node:path'
import {fileURLToPath} from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const contentDir = resolve(__dirname, '../src/content')
const target = resolve(contentDir, 'registry.ts')

function walk(dir) {
  const out = []
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry)
    if (statSync(full).isDirectory()) {
      out.push(...walk(full))
    } else if (entry.endsWith('.mdx')) {
      out.push(full)
    }
  }

  return out
}

const locales = readdirSync(contentDir).filter((name) => {
  const full = join(contentDir, name)
  return statSync(full).isDirectory()
})

const imports = []
const registryByLocale = {}
const paramsList = []
let counter = 0

for (const locale of locales.sort()) {
  const localeDir = join(contentDir, locale)
  registryByLocale[locale] = []

  for (const file of walk(localeDir).sort()) {
    const rel = relative(localeDir, file).split(sep).join('/') // posix-style
    const slug = rel.replace(/\.mdx$/, '') // e.g. "index" or "official-plugins/jira"
    const key = slug === 'index' ? '' : slug
    const segments = key === '' ? [] : key.split('/')

    const ident = `C${counter++}`
    // Import path relative to src/content/registry.ts.
    imports.push(`import ${ident} from './${locale}/${rel}'`)
    registryByLocale[locale].push({ident, key})
    paramsList.push({locale, slug: segments})
  }
}

const registryEntries = Object.entries(registryByLocale)
  .map(([locale, entries]) => {
    const inner = entries.map(({ident, key}) => `    ${JSON.stringify(key)}: ${ident},`).join('\n')
    return `  ${JSON.stringify(locale)}: {\n${inner}\n  },`
  })
  .join('\n')

const paramsLiteral = paramsList
  .map((p) => `  {locale: ${JSON.stringify(p.locale)}, slug: ${JSON.stringify(p.slug)}},`)
  .join('\n')

const banner = `// AUTO-GENERATED by scripts/generate-content-registry.mjs — do not edit by hand.
// Run \`npm run dev\` or \`npm run build\` to regenerate.
/* eslint-disable */
import type {ComponentType} from 'react'
`

const body = `${banner}
${imports.join('\n')}

export const registry: Record<string, Record<string, ComponentType>> = {
${registryEntries}
}

export const contentParams: Array<{locale: string; slug: string[]}> = [
${paramsLiteral}
]
`

mkdirSync(dirname(target), {recursive: true})
writeFileSync(target, body)
console.log(`content-registry: wrote ${target} (${paramsList.length} pages across ${locales.length} locales)`)
